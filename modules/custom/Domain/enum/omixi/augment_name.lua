omixi.util.getAugmentDescription = function(augs)
    local result = ""

    for val = 1, #augs, 2 do
        result = result .. string.gsub(omixi.augment_name[augs[val]], "%d+", augs[val + 1] + 1)

        if val < #augs - 2 then
            result = result .. " / "
        end
    end

    return result
end

